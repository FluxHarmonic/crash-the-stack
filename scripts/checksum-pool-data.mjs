// Metadata-only packaging of actual filtered runtime deals; no search here.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { parseDeals } from './checksum-solve.mjs';

const args = process.argv.slice(2);
const option = (name, fallback) => args.includes(name) ? args[args.indexOf(name) + 1] : fallback;
const dealsFile = option('--deals', 'bench/checksum-reference/deals.scm');
const metricsFile = option('--metrics', 'bench/checksum-reference/runtime-metrics.scm');
const dataFile = option('--data', 'src/crash/checksum/pool/data.sgl');
const manifestFile = option('--manifest', 'bench/checksum-reference/pool-manifest.json');
const expected = Number(option('--expect', '256'));
const producer = option('--producer', 'b3e867b686206c9edf2c0b5a4723591b4000b548');
const backend = option('--backend', 'source');
assert.match(producer, /^[a-f0-9]{40}$/);
assert.ok(['source', 'native'].includes(backend));
const dealsText = fs.readFileSync(dealsFile, 'utf8');
const metricsText = fs.readFileSync(metricsFile, 'utf8');
const deals = parseDeals(dealsText);
assert.equal(deals.length, expected);
assert.ok(expected >= 200 && expected <= 256);
const candidates = new Map(), accepted = new Map();
for (const line of metricsText.trim().split('\n')) {
  let m = line.match(/^\(candidate (\d+) (\d+) (\w+) ([\d.eE+-]+) (\d+) (\d+) (\d+) (\d+)\)$/);
  if (m) candidates.set(`${m[1]}/${m[2]}`, { status: m[3], nodes: +m[5], failed: +m[6], draws: +m[7], needed: +m[8] });
  m = line.match(/^\(accepted (\d+) ([\d.eE+-]+) (\d+) (\d+)\)$/);
  if (m) accepted.set(+m[1], { attempts: +m[3], totalNodes: +m[4] });
}
const seenSeeds = new Set(), seenDecks = new Set();
const records = deals.map(deal => {
  assert.ok(!seenSeeds.has(deal.seed)); seenSeeds.add(deal.seed);
  const packets = [...deal.pyramid, ...deal.stock];
  assert.deepEqual([...packets].sort((a, b) => a - b), Array.from({ length: 52 }, (_, i) => i));
  const signature = packets.join(','); assert.ok(!seenDecks.has(signature)); seenDecks.add(signature);
  const a = accepted.get(deal.seed); assert.ok(a, `accepted ledger for seed ${deal.seed}`);
  const c = candidates.get(`${deal.seed}/${a.attempts}`); assert.ok(c);
  assert.equal(c.status, 'solved'); assert.ok(c.nodes <= 100000);
  assert.ok(c.draws >= 8 && c.failed >= 20 && 100 * c.needed <= 55 * c.draws,
    `unchanged difficulty filter for seed ${deal.seed}`);
  return { ...deal, ...a, ...c };
});
assert.deepEqual(records.map(r => r.seed), Array.from({ length: expected }, (_, i) => i + 1));
// Bound constructor arity: the pinned register VM has 255 registers.
const chunks = [];
for (let at = 0; at < records.length; at += 16) {
  const rows = records.slice(at, at + 16).map(r => `          (vector ${r.seed}\n                  (vector ${r.pyramid.join(' ')})\n                  (list ${r.stock.join(' ')})\n                  ${r.draws} ${r.needed} ${r.failed} ${r.attempts} ${r.totalNodes})`).join('\n');
  chunks.push(`        (vector\n${rows})`);
}
const source = `;;; Generated by scripts/checksum-pool-data.mjs from actual proved deals.\n;;; Row: seed, pyramid, feed, draws, useful draws, failed states, attempts, nodes.\n;;; Construct bounded chunks; do not use a large quoted datum.\n\n(define-library (crash checksum pool data)\n  (export CHECKSUM-POOL-DEALS)\n  (begin\n    (define CHECKSUM-POOL-DEALS\n      (vector-append\n${chunks.join('\n')}))))\n`;
const hash = text => createHash('sha256').update(text).digest('hex');
const manifest = { count: expected, complete256: expected === 256, producer, backend,
  dealsSha256: hash(dealsText), metricsSha256: hash(metricsText), dataSha256: hash(source),
  filter: { nodeBudget: 100000, passes: 3, minimumDraws: 8, minimumFailedStates: 20, maximumUsefulDrawPercent: 55 },
  entries: records.map(({ seed, draws, needed, failed, attempts, totalNodes }) => ({ seed, draws, needed, failed, attempts, totalNodes })) };
for (const file of [dataFile, manifestFile]) fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(dataFile, source);
fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2) + '\n');
console.log(JSON.stringify({ count: expected, complete256: manifest.complete256, producer, backend,
  dealsSha256: manifest.dealsSha256, dataSha256: manifest.dataSha256 }));
